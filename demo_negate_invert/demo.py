#!/usr/bin/env python3
"""Render the same SVG layout as a normal and an inverted preview.

The layout (``layout.svg``) is 480×320 (four times the 240×160 minimum) and
references local raster assets generated by ``make_assets.py``.  Four PNG
files are produced:

===========================  ======================  ======================
file                          negate_colors           invert_images
===========================  ======================  ======================
``output/normal.png``         off                     off
``output/negate-only.png``    on                      off
``output/invert-only.png``    off                     on
``output/both.png``           on                      on
===========================  ======================  ======================

Each variant is checked against the normal render:

* vector samples (fill, gradient stop, pattern swatch, text) change only
  when ``negate_colors`` is on, and then become their RGB complement;
* opaque raster samples change only when ``invert_images`` is on, and then
  become their RGB complement;
* the semi-transparent raster sample is compared through its alpha: the
  composited result must be the inverted pixel over the inverted background,
  which proves the image itself was inverted rather than flattened;
* fully transparent regions must show the same color as a background-only
  probe pixel of the same render, in every variant.  A transparent pixel
  turned black would break this;
* rendering the same assets alone on a transparent canvas checks the alpha
  channel directly (0 stays 0, 128 stays 128) with ``negate_colors`` and
  ``invert_images`` both on and off.

Usage::

    python demo_negate_invert/demo.py

The Cairo shared library must be reachable; see ``NATIVE-RUNTIME.md``.

"""

from io import BytesIO
from pathlib import Path

from PIL import Image

from cairosvg import surface

HERE = Path(__file__).parent
LAYOUT = HERE / 'layout.svg'
OUTPUT = HERE / 'output'

# Points of the 480×320 layout, classified by what they show.
#
# ``vector`` pixels are painted by SVG shapes, gradients, patterns or text:
# only ``negate_colors`` changes them, and always by RGB complement.
# ``raster`` pixels are opaque image pixels: only ``invert_images`` changes
# them, by RGB complement.
VECTOR_POINTS = {
    'vector fill': (40, 40),
    'gradient stop': (240, 40),
    'pattern swatch': (330, 10),
    'label text': (20, 216),
}

RASTER_POINTS = {
    'rgba opaque': (30, 150),
    # Opaque pixels of the palette image and of the RGB+tRNS image.
    'palette opaque': (130, 150),
    'rgb colour key opaque': (230, 150),
    # EXIF orientation: the red band must be on top and green below.
    'exif jpeg top': (340, 150),
    'exif jpeg bottom': (340, 200),
    'exif png top': (390, 150),
    'exif png bottom': (390, 200),
    # The same image reused inside a clip path.
    'clipped reuse': (56, 276),
    # CMYK TIFF converted to RGB before inversion.
    'cmyk red': (230, 250),
    'cmyk green': (290, 250),
    # 16-bit grayscale scaled to 8 bits instead of being clamped.
    'gray16 mid': (230, 308),
    'gray16 high': (290, 308),
}

SEMI_POINT = (80, 150)  # RGBA quadrant with alpha 128

# Regions that must stay transparent.  The layout paints an opaque vector
# background below, so each of these must equal a background-only probe
# pixel of the same render.
TRANSPARENT_POINTS = {
    'rgba transparent quadrant': (30, 200),
    'palette transparent index': (190, 150),
    'rgb colour-key pixel': (290, 150),
    'pattern tile border': (330, 20),
}
BACKGROUND_PROBE = (470, 130)

# Assets rendered alone on a transparent 64×64 canvas.  Expected alphas do
# not depend on the options; the RGB channels of visible pixels do.
ALPHA_PROBES = {
    'rgba_quadrants.png': {
        'transparent quadrant': ((16, 48), 0),
        'semi-transparent quadrant': ((48, 16), 128),
        'opaque quadrant': ((16, 16), 255),
    },
    'palette_transparent.png': {
        'transparent palette index': ((48, 16), 0),
        'opaque palette index': ((16, 16), 255),
    },
    'rgb_colour_key.png': {
        'colour-key pixel': ((48, 16), 0),
        'opaque pixel': ((16, 16), 255),
    },
}


def _close(actual, expected, tolerance=3):
    return all(
        abs(a - e) <= tolerance for a, e in zip(actual, expected))


def _complement(pixel):
    return (255 - pixel[0], 255 - pixel[1], 255 - pixel[2], pixel[3])


def _asset_fetcher(url, resource_type):
    """Resolve only files inside the demo ``assets`` folder.

    The layout itself is passed as a byte string and the alpha probes use
    this fetcher instead of ``unsafe=True``, so the demo does not widen
    CairoSVG’s default resource access: anything outside ``assets/`` raises
    ``FileNotFoundError``.

    """
    name = url.rsplit('/', 1)[-1].split('#')[0]
    assets = (HERE / 'assets').resolve()
    path = (assets / name).resolve()
    if path.parent != assets:
        raise FileNotFoundError(url)
    return path.read_bytes()


def render(negate_colors, invert_images):
    """Render ``layout.svg`` with the given options."""
    return surface.PNGSurface.convert(
        bytestring=LAYOUT.read_bytes(), url_fetcher=_asset_fetcher,
        negate_colors=negate_colors, invert_images=invert_images)


def render_asset(asset, negate_colors, invert_images):
    """Render one raster asset alone on a transparent canvas."""
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" '
        'xmlns:xlink="http://www.w3.org/1999/xlink" '
        'width="64" height="64">'
        f'<image width="64" height="64" xlink:href="{asset}"/>'
        '</svg>')
    png = surface.PNGSurface.convert(
        bytestring=svg.encode(), url_fetcher=_asset_fetcher,
        negate_colors=negate_colors, invert_images=invert_images)
    return Image.open(BytesIO(png)).convert('RGBA')


def report(name, image, normal, negate_colors, invert_images, semi_source):
    """Check one variant against the normal render.

    ``semi_source`` is the semi-transparent asset pixel as rendered alone
    (RGBA), so its true alpha and color are known even though the layout
    composites it over an opaque background.

    """
    print(f'\n{name}  (negate_colors={negate_colors}, '
          f'invert_images={invert_images})')
    failures = []
    background = image.getpixel(BACKGROUND_PROBE)
    normal_background = normal.getpixel(BACKGROUND_PROBE)
    if negate_colors:
        expected_background = _complement(normal_background)
        if not _close(background, expected_background):
            failures.append(
                f'layout background {background} is not the complement of '
                f'{normal_background}')

    for label, point in VECTOR_POINTS.items():
        expected = (
            _complement(normal.getpixel(point)) if negate_colors
            else normal.getpixel(point))
        actual = image.getpixel(point)
        status = 'ok' if _close(actual, expected) else 'FAIL'
        if status == 'FAIL':
            failures.append(f'{label} at {point}')
        print(f'  {status:4s} {label:28s} {actual} expected {expected}')

    for label, point in RASTER_POINTS.items():
        expected = (
            _complement(normal.getpixel(point)) if invert_images
            else normal.getpixel(point))
        actual = image.getpixel(point)
        status = 'ok' if _close(actual, expected) else 'FAIL'
        if status == 'FAIL':
            failures.append(f'{label} at {point}')
        print(f'  {status:4s} {label:28s} {actual} expected {expected}')

    # Semi-transparent pixel: take the asset's own color and alpha, invert
    # the color if requested, and composite over the background of this
    # render (which ``negate_colors`` may itself have negated).  If the
    # inversion had flattened the alpha, the composited result would be
    # opaque and differ.
    alpha = semi_source[3] / 255
    source = semi_source[:3]
    if invert_images:
        source = tuple(255 - value for value in source)
    expected = tuple(
        round(source[index] * alpha + background[index] * (1 - alpha))
        for index in range(3)) + (255,)
    actual = image.getpixel(SEMI_POINT)
    status = 'ok' if _close(actual, expected) else 'FAIL'
    if status == 'FAIL':
        failures.append(f'semi-transparent raster at {SEMI_POINT}')
    print(f'  {status:4s} {"rgba semi-transparent":28s} {actual} '
          f'expected {expected}')

    for label, point in TRANSPARENT_POINTS.items():
        actual = image.getpixel(point)
        status = 'ok' if _close(actual, background) else 'FAIL'
        if status == 'FAIL':
            failures.append(f'{label} at {point}')
        print(f'  {status:4s} {label:28s} {actual} background {background}')
    if failures:
        print('  FAILED: ' + ', '.join(failures))
    return failures


def alpha_report(normal_assets, negate_colors, invert_images):
    """Check alpha and colors of assets rendered alone, without background."""
    print(f'\n  assets alone  (negate_colors={negate_colors}, '
          f'invert_images={invert_images})')
    failures = []
    for asset, probes in ALPHA_PROBES.items():
        image = render_asset(asset, negate_colors, invert_images)
        reference = normal_assets[asset]
        for label, (point, expected_alpha) in probes.items():
            actual = image.getpixel(point)
            normal = reference.getpixel(point)
            status = 'ok' if actual[3] == expected_alpha else 'FAIL'
            if status == 'FAIL':
                failures.append(f'{asset} {label} alpha')
            if expected_alpha == 255:
                expected = (
                    _complement(normal) if invert_images else normal)
                if not _close(actual, expected):
                    status = 'FAIL'
                    failures.append(f'{asset} {label} color')
            print(f'    {status:4s} {asset:26s} {label:26s} {actual} '
                  f'alpha {expected_alpha}')
    return failures


def _make_assets():
    """Run ``make_assets.py`` without requiring it on ``sys.path``."""
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        'demo_make_assets', HERE / 'make_assets.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.main()


def main():
    OUTPUT.mkdir(exist_ok=True)
    if not (HERE / 'assets' / 'rgba_quadrants.png').exists():
        _make_assets()
    normal_png = render(False, False)
    normal = Image.open(BytesIO(normal_png)).convert('RGBA')
    variants = (
        ('normal', False, False),
        ('negate-only', True, False),
        ('invert-only', False, True),
        ('both', True, True),
    )
    normal_assets = {
        asset: render_asset(asset, False, False) for asset in ALPHA_PROBES}
    semi_source = normal_assets['rgba_quadrants.png'].getpixel((48, 16))

    all_failures = []
    for name, negate_colors, invert_images in variants:
        png = render(negate_colors, invert_images)
        (OUTPUT / f'{name}.png').write_bytes(png)
        image = Image.open(BytesIO(png)).convert('RGBA')
        all_failures += report(
            name, image, normal, negate_colors, invert_images, semi_source)
        all_failures += alpha_report(
            normal_assets, negate_colors, invert_images)

    # Disabled options must reproduce the default output exactly.
    baseline = render(False, False)
    if (OUTPUT / 'normal.png').read_bytes() != baseline:
        all_failures.append('normal.png differs from the default call')
    else:
        print('\nnormal.png is byte-identical to the default call.')

    if all_failures:  # pragma: no cover - interactive demo
        raise SystemExit(f'{len(all_failures)} checks failed')

    print('\nAll checks passed.  Both options are applied exactly once,')
    print('transparent pixels stay transparent and geometry is preserved.')
    print(f'PNG files written to {OUTPUT}')


if __name__ == '__main__':
    main()
