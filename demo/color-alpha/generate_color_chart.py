#!/usr/bin/env python3
"""Regenerable CSS color comparison chart for CairoSVG.

The chart paints rows of color swatches using equivalent CSS color notations
(hex with alpha, legacy comma ``rgb()`` / ``rgba()``, the CSS Color 4
space-separated and slash-alpha syntax, named colors) and compares the real
pixels CairoSVG renders for each equivalence class. It also exercises:

* presentation attributes vs. inline ``style`` declarations,
* fill, stroke and gradient stop colors,
* color alpha combined with fill-opacity / stop-opacity / group opacity,
* source-over compositing of semi-transparent overlapping shapes,
* repeated exports (the PNG is rendered twice and compared byte for byte).

No pre-rendered bitmap is used: the SVG is generated by this script and
rendered through the local CairoSVG + Cairo stack every time.

Usage::

    python demo/color-alpha/generate_color_chart.py [output_directory]

"""

import io
import pathlib
import sys

from PIL import Image

from cairosvg import svg2png

WIDTH, HEIGHT = 600, 880
SWATCH_W, SWATCH_H = 86, 22
LEFT = MARGIN = 10
LABEL_H, BAND_H, ROW_GAP = 26, SWATCH_H + 6, 14
ROW_STEP = LABEL_H + BAND_H + ROW_GAP
TOP = 40

# All notations in a tuple describe the *same* color. A = 128/255.
A128 = '0.5019607843137255'
P128 = '50.19607843137255%'
# 4-digit hex duplicates the nibble: 0x88 -> 136/255.
A136 = '0.5333333333333333'
P136 = '53.333333333333336%'

ROWS = [
    ('opaque red, equivalent notations', [
        ('#f00', '#ff0000', 'rgb(255,0,0)', 'rgb(255 0 0)'),
    ]),
    ('semi-transparent red, alpha 128/255', [
        ('#ff000080', f'rgba(255,0,0,{A128})',
         f'rgb(255 0 0 / {A128})', f'rgb(100% 0% 0% / {P128})'),
    ]),
    ('short hex #RGBA, alpha 136/255', [
        ('#f008', '#ff000088', f'rgba(255,0,0,{A136})',
         f'rgb(255 0 0 / {P136})'),
    ]),
    ('percentage channels, 50% gray', [
        ('#808080', 'rgb(50%,50%,50%)', 'rgb(50% 50% 50%)',
         'rgb(128 128 128)'),
    ]),
    ('attribute vs inline style vs named color', [
        ('red', 'RED'.lower(), 'rgb(255,0,0)', '__style__:rgb(255 0 0)'),
    ]),
    ('fill-opacity 0.5 combined with color alpha 0.5', [
        ('__fillopacity__:#ff000080:0.5',
         '__fillopacity__:rgba(255,0,0,0.5019607843137255):0.5',
         '__fillopacity__:rgb(255 0 0 / 50.19607843137255%):0.5'),
        ('__plain__:red:0.25098039215686274',),
    ]),
    ('stroke colors with alpha', [
        ('__stroke__:#ff000080',
         '__stroke__:rgba(255,0,0,0.5019607843137255)',
         '__stroke__:rgb(255 0 0 / 50.19607843137255%)',
         '__stroke__:rgba(100%,0%,0%,50.19607843137255%)'),
    ]),
    ('gradient stops with alpha', [
        ('__gradient__:#00ff0080:#ffffffff',
         '__gradient__:rgba(0,255,0,0.5019607843137255):rgb(255 255 255/1)',
         '__gradient__:rgb(0 255 0/50.19607843137255%):#ffffff',
         '__gradient__:rgba(0%,100%,0%,50.19607843137255%):#ffffff'),
    ]),
    ('stop alpha 0.5 x stop-opacity 0.5 = 0.25', [
        ('__stopopacity__:#ff000080:0.5',
         '__stopopacity__:rgba(255,0,0,0.5019607843137255):0.5',
         '__stopopacity__:rgb(255 0 0 / 50.19607843137255%):0.5'),
        ('__plain__:red:0.25098039215686274',),
    ]),
    ('group opacity 0.5 over color alpha 0.5', [
        ('__group__:#ff000080:0.5',
         '__group__:rgba(255,0,0,0.5019607843137255):0.5',
         '__group__:rgb(255 0 0 / 50.19607843137255%):0.5'),
        ('__plain__:red:0.25098039215686274',),
    ]),
    ('overlap: two alpha-0.5 layers, source-over 0.75', [
        ('__overlap__:#ff000080',),
        ('__overlap__:rgba(255,0,0,0.5019607843137255)',
         '__overlap__:rgb(255 0 0 / 50.19607843137255%)',
         '__overlap__:rgba(100%,0%,0%,50.19607843137255%)'),
    ]),
    ('invalid color fallback does not abort the document', [
        ('hsl(0 100% 50%)', 'rgb(255, 0, 0 / 0.5)', 'rgb(255 0%, 0)',
         '#12345'),
    ]),
]


def esc(text):
    return (text.replace('&', '&amp;').replace('<', '&lt;')
            .replace('>', '&gt;').replace('"', '&quot;'))


def row_label_y(row):
    """Baseline y of the label text for row index ``row``."""
    return TOP + row * ROW_STEP + 14


def row_band_y(row):
    """Top y of the swatch band for row index ``row``."""
    return TOP + row * ROW_STEP + LABEL_H


def swatch_rect(notation, x, y, w=SWATCH_W, h=SWATCH_H):
    """Return SVG markup painting one swatch from ``notation``."""
    title = f'<title>{esc(notation)}</title>'
    if notation.startswith('__style__:'):
        value = notation.split(':', 1)[1]
        return (f'<g>{title}<rect x="{x}" y="{y}" width="{w}" height="{h}" '
                f'style="fill: {esc(value)}"/></g>')
    if notation.startswith('__stroke__:'):
        value = notation.split(':', 1)[1]
        # Stroke confined to the swatch band: a centered horizontal line whose
        # width never crosses the row boundaries.
        thickness = h - 8
        line_y = y + h / 2
        return (f'<g>{title}<line x1="{x + 4}" y1="{line_y}" '
                f'x2="{x + w - 4}" y2="{line_y}" stroke="{esc(value)}" '
                f'stroke-width="{thickness}" stroke-linecap="butt"/></g>')
    if notation.startswith('__fillopacity__:'):
        _, value, op = notation.split(':')
        return (f'<g>{title}<rect x="{x}" y="{y}" width="{w}" height="{h}" '
                f'fill="{esc(value)}" fill-opacity="{op}"/></g>')
    if notation.startswith('__plain__:'):
        _, value, op = notation.split(':')
        return (f'<g>{title}<rect x="{x}" y="{y}" width="{w}" height="{h}" '
                f'fill="{esc(value)}" fill-opacity="{op}"/></g>')
    if notation.startswith('__gradient__:'):
        gid = f'g{x}_{y}'.replace('-', 'm')
        _, start, end = notation.split(':')
        return (
            f'<g>{title}'
            f'<linearGradient id="{gid}" x1="0" y1="0" x2="1" y2="0">'
            f'<stop offset="0" stop-color="{esc(start)}"/>'
            f'<stop offset="1" stop-color="{esc(end)}"/></linearGradient>'
            f'<rect x="{x}" y="{y}" width="{w}" height="{h}" '
            f'fill="url(#{gid})"/></g>')
    if notation.startswith('__stopopacity__:'):
        gid = f's{x}_{y}'.replace('-', 'm')
        _, value, op = notation.split(':')
        return (
            f'<g>{title}'
            f'<linearGradient id="{gid}" x1="0" y1="0" x2="1" y2="0">'
            f'<stop offset="0" stop-color="{esc(value)}" stop-opacity="{op}"/>'
            f'<stop offset="1" stop-color="{esc(value)}" stop-opacity="{op}"/>'
            f'</linearGradient>'
            f'<rect x="{x}" y="{y}" width="{w}" height="{h}" '
            f'fill="url(#{gid})"/></g>')
    if notation.startswith('__group__:'):
        _, value, op = notation.split(':')
        return (
            f'<g opacity="{op}">{title}'
            f'<g><rect x="{x}" y="{y}" width="{w / 2}" height="{h}" '
            f'fill="{esc(value)}"/>'
            f'<rect x="{x + w / 2}" y="{y}" width="{w / 2}" height="{h}" '
            f'fill="{esc(value)}"/></g></g>')
    if notation.startswith('__overlap__:'):
        value = notation.split(':', 1)[1]
        return (
            f'<g>{title}'
            f'<rect x="{x}" y="{y}" width="{w * 0.75:.1f}" height="{h}" '
            f'fill="{esc(value)}"/>'
            f'<rect x="{x + w * 0.25:.1f}" y="{y}" width="{w * 0.75:.1f}" '
            f'height="{h}" fill="{esc(value)}"/></g>')
    return (f'<g>{title}<rect x="{x}" y="{y}" width="{w}" height="{h}" '
            f'fill="{esc(notation)}"/></g>')


def build_svg():
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" '
        f'height="{HEIGHT}" viewBox="0 0 {WIDTH} {HEIGHT}" '
        f'font-family="monospace" font-size="11">',
        '<rect width="100%" height="100%" fill="white"/>',
        f'<text x="{MARGIN}" y="20" font-size="14" font-weight="bold">'
        'CairoSVG CSS color alpha — equivalent notation comparison</text>',
    ]
    y = TOP
    for label, groups in ROWS:
        # Label on its own line, never overlapping the swatch band below.
        parts.append(
            f'<text x="{MARGIN}" y="{y + 14}" fill="#222">{esc(label)}</text>')
        band_y = y + LABEL_H
        x = LEFT
        for group in groups:
            for notation in group:
                parts.append(swatch_rect(notation, x, band_y))
                x += SWATCH_W + 4
        y += ROW_STEP
    parts.append('</svg>')
    return ''.join(parts)


def render(svg_text):
    return svg2png(bytestring=svg_text.encode(),
                   output_width=WIDTH, output_height=HEIGHT)


def swatch_center_groups():
    """Yield ``(label, [[(notation, x, y), ...], ...])`` grouped like ROWS."""
    for row, (label, groups) in enumerate(ROWS):
        x = LEFT + SWATCH_W // 2
        y = row_band_y(row) + SWATCH_H // 2
        row_groups = []
        for group in groups:
            centers = []
            for notation in group:
                centers.append((notation, x, y))
                x += SWATCH_W + 4
            row_groups.append(centers)
        yield label, row_groups


def compare(image):
    """Compare pixels of every equivalence row and return a text report.

    Notations within one group use the same numeric precision and must render
    byte-identical pixels. Groups of the same row describe the same
    conceptual color, but hex alpha is quantized on 8 bits while functional
    notations keep float precision, so distinct groups are compared with a
    small compositing tolerance. The invalid-color row instead checks the
    historical opaque-black fallback.

    """
    lines = []
    all_match = True
    for label, groups in swatch_center_groups():
        if label.startswith('invalid color'):
            pixels = [
                image.getpixel((x, y))
                for centers in groups for _, x, y in centers]
            ok = all(pixel == (0, 0, 0, 255) for pixel in pixels)
            all_match &= ok
            lines.append(
                f"{'PASS' if ok else 'FAIL'}  {label}: "
                f'{len(pixels)} invalid colors -> opaque black fallback')
            continue

        group_pixels = []
        row_ok = True
        for centers in groups:
            pixels = [image.getpixel((x, y)) for _, x, y in centers]
            within = tuple(
                max(values) - min(values)
                for values in zip(*pixels))
            row_ok &= within == (0, 0, 0, 0)
            group_pixels.append(pixels[0])
        if len(group_pixels) > 1:
            cross_spread = tuple(
                max(values) - min(values)
                for values in zip(*group_pixels))
            row_ok &= max(cross_spread) <= 2
        else:
            cross_spread = (0, 0, 0, 0)
        all_match &= row_ok
        lines.append(
            f"{'PASS' if row_ok else 'FAIL'}  {label}: within-group exact, "
            f'cross-group spread {cross_spread}, reference '
            f'{group_pixels[0]}')
    return all_match, lines


def main(output_dir):
    output_dir = pathlib.Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    svg_text = build_svg()
    svg_path = output_dir / 'color_chart.svg'
    png_path = output_dir / 'color_chart.png'
    report_path = output_dir / 'color_chart_report.txt'
    svg_path.write_text(svg_text, encoding='utf-8')

    png_bytes = render(svg_text)
    png_path.write_bytes(png_bytes)

    # Repeated export must be byte-identical.
    repeat = render(svg_text)
    repeat_ok = repeat == png_bytes

    image = Image.open(io.BytesIO(png_bytes)).convert('RGBA')
    assert image.size == (WIDTH, HEIGHT)
    pixels_match, report_lines = compare(image)

    report = [
        'CairoSVG CSS color alpha comparison chart',
        f'canvas: {WIDTH}x{HEIGHT} RGBA, rendered by local CairoSVG/Cairo',
        f'repeated export byte-identical: {repeat_ok}',
        '',
        *report_lines,
        '',
        'Notes:',
        '- rows group notations that must resolve to the same RGBA value;',
        '- pixels are read back from the freshly rendered PNG, no reference '
        'bitmap is used;',
        '- invalid colors keep the historical opaque-black fallback while '
        'sibling shapes still render.',
    ]
    report_path.write_text('\n'.join(report) + '\n', encoding='utf-8')
    print('\n'.join(report))

    if not (pixels_match and repeat_ok):
        sys.exit(1)


if __name__ == '__main__':
    target = sys.argv[1] if len(sys.argv) > 1 else \
        pathlib.Path(__file__).parent / 'output'
    main(target)
